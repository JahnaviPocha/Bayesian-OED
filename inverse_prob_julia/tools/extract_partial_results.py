#!/usr/bin/env python3
"""
Reconstruct results from a SLURM log of a still-running (or killed) design run.

The design scripts only write plots and Excel after their loop finishes, so a
job that hits the wall clock leaves nothing behind. Everything they print along
the way is enough to rebuild most of that output, and this tool does it without
importing juliacall, so it runs on the login node in seconds.

    python tools/extract_partial_results.py slurm_logs/bayes_design_meoh_RBS_8883353.out

Writes into results/<logname>_partial/: parameter_history.csv, experiments.csv,
variable_explorer_data.xlsx, and the convergence plots.

What comes back per job type:

  bayes_design_meoh_RBS       designs, responses, parameter history  (complete)
  bayes_design_meoh_FIO_RBS   responses, information, parameters; the chosen
                              designs are never printed in the BO loop, so
                              they cannot be recovered
  bayes_design_random_*       responses and parameter history; the design is a
                              deterministic Halton sequence, so it is
                              regenerated by re-running rpg(), not parsed

The raw measurement tensor Y_full is never printed and is lost in every case.

Noise attribution: the three noise levels run as concurrent processes sharing
one stdout with nothing on the line saying which is which. Records are assigned
to noise levels by their position within each round, in the order the noise
headers first appear. That holds only while the processes stay in lockstep, so
the parameter trajectories are checked for continuity afterwards and any
suspicious jump is reported. Use --noise-order to override.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

PROJECT_DIR = Path(__file__).resolve().parent.parent

FLOAT = r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?"


# ============================================================
# CONSTANTS, READ FROM THE DESIGN SCRIPT ITSELF
# ============================================================

def load_script_constants(script_path):
    """
    Pull TRUE_PARAMS and friends out of a design script without importing it.

    Importing would pull in call_to_KPE_code_meoh and start a Julia runtime,
    which is far too heavy for a log parse. The values are plain module-level
    literals, so the AST is enough, and reading them here keeps this tool in
    step with the script instead of duplicating its numbers.
    """
    # The FIO script spells the true values TRUE_PARAMS_PHYSICAL.
    aliases = {"TRUE_PARAMS_PHYSICAL": "TRUE_PARAMS"}
    wanted = {
        "TRUE_PARAMS",
        "TRUE_PARAMS_PHYSICAL",
        "PARAM_LOWER",
        "PARAM_UPPER",
        "PARAMETER_SHORT_NAMES",
        "N_UNKNOWN_PARAMETERS",
        "MIN_ESTIMATION_EXPERIMENTS",
        "N_INIT",
    }
    found = {}
    tree = ast.parse(Path(script_path).read_text(encoding="utf-8"))

    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if not isinstance(target, ast.Name) or target.id not in wanted:
                continue
            value = node.value
            # np.array([...], dtype=float) -> take the list argument
            if isinstance(value, ast.Call) and value.args:
                value = value.args[0]
            try:
                found[aliases.get(target.id, target.id)] = ast.literal_eval(value)
            except ValueError:
                pass

    return found


def normalize_parameters(params, lower, upper):
    params = np.asarray(params, dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        return (np.log10(params) - np.log10(lower)) / (
            np.log10(upper) - np.log10(lower)
        )


# ============================================================
# LOW-LEVEL LOG READING
# ============================================================

def read_bracketed(lines, index, marker):
    """
    Read a numpy array printed across several lines.

    Arrays wrap at 4 values per line, so `Estimated parameters: [1.16e-01 ...`
    continues until the brackets balance.
    """
    text = lines[index].split(marker, 1)[1]
    i = index
    while text.count("[") > text.count("]") and i + 1 < len(lines):
        i += 1
        text += " " + lines[i]

    body = text[text.index("[") + 1: text.index("]")] if "]" in text else text
    return [float(v) for v in re.findall(FLOAT, body)], i


def noise_headers(lines):
    """Noise levels in the order their headers first reach the log."""
    # "Noise level: 1e-05" in the RBS scripts, "noise_level = 1e-05" in FIO.
    pattern = re.compile(r"\s*noise[ _]level\s*[:=]\s*(" + FLOAT + ")", re.IGNORECASE)
    order = []
    for line in lines:
        match = pattern.match(line)
        if match:
            value = float(match.group(1))
            if value not in order:
                order.append(value)
        if len(order) >= 3:
            break
    return order


# ============================================================
# PER-JOB-TYPE PARSERS
# ============================================================

def parse_meoh_rbs(lines):
    """
    Bayesian-optimisation methanol run: designs and responses are both printed.

    Records key on the BO iteration number. Each iteration adds 2 experiments
    on top of N_INIT, so the experiment count is recoverable from the number.
    """
    records = []
    open_records = []
    current = None
    i = 0

    while i < len(lines):
        line = lines[i]

        match = re.match(r"--- BO Iteration (\d+) ---", line)
        if match:
            # Several workers are normally mid-iteration at once, so records
            # stay open and the estimates that follow are matched to them in
            # arrival order.
            current = {"key": int(match.group(1)), "x": [], "y": [], "params": None}
            records.append(current)
            open_records.append(current)
            i += 1
            continue

        if current is not None and "x=[" in line:
            values, i = read_bracketed(lines, i, "x=[")
            tail = lines[i]
            methanol = re.search(r"methanol=(" + FLOAT + ")", tail)
            current["x"].append(values)
            current["y"].append(float(methanol.group(1)) if methanol else np.nan)
            i += 1
            continue

        if open_records and line.startswith("Estimated parameters:"):
            values, i = read_bracketed(lines, i, "Estimated parameters:")
            open_records.pop(0)["params"] = values
            i += 1
            continue

        i += 1

    return records, sum(1 for r in records if r["params"] is None)


def parse_meoh_fio_rbs(lines):
    """
    Fisher-information methanol run.

    `--- BO Iteration ... ---` carries no number here, so records key on
    `Batch update: total experiments = N`, which arrives at the end of the
    iteration. Fields are therefore collected into a pending record and sealed
    when that line appears. The chosen designs are never printed.
    """
    records = []
    pending = {"y": [], "params": None, "information": None}
    i = 0

    while i < len(lines):
        line = lines[i]

        match = re.search(r"Candidate done: methanol=(" + FLOAT + ")", line)
        if match:
            pending["y"].append(float(match.group(1)))
            i += 1
            continue

        match = re.match(r"Cumulative information = (" + FLOAT + ")", line)
        if match:
            pending["information"] = float(match.group(1))
            i += 1
            continue

        if line.startswith("Estimated physical parameters ="):
            values, i = read_bracketed(lines, i, "Estimated physical parameters =")
            pending["params"] = values
            i += 1
            continue

        match = re.match(r"Batch update: total experiments = (\d+)", line)
        if match:
            pending["key"] = int(match.group(1))
            pending["x"] = []
            records.append(pending)
            pending = {"y": [], "params": None, "information": None}
            i += 1
            continue

        i += 1

    return records, sum(1 for r in records if r["params"] is None)


def parse_random(lines):
    """
    Random-design run: one record per experiment, parameters only once the
    run passes MIN_ESTIMATION_EXPERIMENTS. Designs are not printed.
    """
    records = []
    current = None
    i = 0

    while i < len(lines):
        line = lines[i]

        match = re.match(r"Experiment (\d+)/(\d+)", line)
        if match:
            current = {
                "key": int(match.group(1)),
                "x": [],
                "y": [],
                "params": None,
                "information": None,
            }
            records.append(current)
            i += 1
            continue

        if current is not None:
            match = re.match(r"CH3OH outlet fraction = (" + FLOAT + ")", line)
            if match:
                current["y"].append(float(match.group(1)))
                i += 1
                continue

            if line.startswith("Estimated physical parameters ="):
                values, i = read_bracketed(lines, i, "Estimated physical parameters =")
                current["params"] = values
                i += 1
                continue

        i += 1

    return records, 0


PARSERS = {
    "meoh_RBS": (parse_meoh_rbs, "bayes_design_meoh_RBS.py"),
    "meoh_FIO_RBS": (parse_meoh_fio_rbs, "bayes_design_meoh_FIO_RBS.py"),
    "random_meoh_RBS": (parse_random, "bayes_design_random_meoh_RBS.py"),
    "random_ROM_asymptotic": (parse_random, "bayes_design_random_ROM_asymptotic.py"),
}


def detect_kind(log_path, lines):
    name = Path(log_path).name
    for kind in PARSERS:
        if f"bayes_design_{kind}_" in name:
            return kind

    head = "\n".join(lines[:400])
    if "METHANOL FIO" in head:
        return "meoh_FIO_RBS"
    if "RANDOM DESIGN" in head:
        return "random_meoh_RBS"
    return "meoh_RBS"


# ============================================================
# NOISE ATTRIBUTION
# ============================================================

def assign_noise(records, noises):
    """
    Attribute each record to a noise level by its slot within its round.

    The concurrent workers stay in lockstep, so the k-th record carrying a
    given key belongs to the k-th noise level. Nothing in the log confirms
    this, which is what check_continuity is for.
    """
    seen = {}
    for record in records:
        slot = seen.get(record["key"], 0)
        seen[record["key"]] = slot + 1
        record["slot"] = slot
        record["noise"] = noises[slot] if slot < len(noises) else None
    return [r for r in records if r["noise"] is not None]


def check_continuity(records, noises, n_params):
    """
    Look for parameter trajectories that jump by orders of magnitude.

    Two different things produce a jump. A wrong slot assignment makes one
    trajectory teleport onto another's values, and that shows up in a single
    noise level at a given round. An estimator that has simply landed in a
    different basin shows up in all three at once, because the noise levels
    share an initial design and RNG seed and so track each other closely.
    Rounds are classified by how many noise levels jump together.
    """
    jumps = {}
    for noise in noises:
        series = [r for r in records if r["noise"] == noise and r["params"]]
        series.sort(key=lambda r: r["key"])
        for previous, current in zip(series, series[1:]):
            a = np.asarray(previous["params"], dtype=float)
            b = np.asarray(current["params"], dtype=float)
            if a.shape != b.shape or a.size != n_params:
                continue
            with np.errstate(divide="ignore", invalid="ignore"):
                decades = np.nanmax(
                    np.abs(np.log10(np.abs(b) + 1e-30) - np.log10(np.abs(a) + 1e-30))
                )
            if decades > 2.0:
                jumps.setdefault(current["key"], []).append((noise, decades))

    shared, isolated = [], []
    for key in sorted(jumps):
        entries = jumps[key]
        detail = ", ".join(f"{noise:.0e} ({d:.1f} dec)" for noise, d in entries)
        if len(entries) >= min(3, len(noises)):
            shared.append(f"  round {key}: all noise levels jump - {detail}")
        else:
            isolated.append(f"  round {key}: {detail}")
    return shared, isolated


# ============================================================
# ASSEMBLY AND OUTPUT
# ============================================================

def build_frames(records, noises, constants, kind):
    n_params = int(constants.get("N_UNKNOWN_PARAMETERS", 9))
    names = constants.get("PARAMETER_SHORT_NAMES", [f"p{i+1}" for i in range(n_params)])
    true_params = np.asarray(constants["TRUE_PARAMS"], dtype=float)
    lower = np.asarray(constants["PARAM_LOWER"], dtype=float)
    upper = np.asarray(constants["PARAM_UPPER"], dtype=float)
    n_init = int(constants.get("N_INIT", constants.get("MIN_ESTIMATION_EXPERIMENTS", 10)))

    def experiment_count(record):
        if kind == "meoh_RBS":
            return n_init + 2 * record["key"]
        return record["key"]

    history_rows = []
    experiment_rows = []

    for record in sorted(records, key=lambda r: (r["noise"], r["key"])):
        n_exp = experiment_count(record)

        for offset, y in enumerate(record["y"]):
            row = {
                "noise": f"{record['noise']:.0e}",
                "experiment": n_exp - len(record["y"]) + offset + 1,
                "methanol": y,
            }
            if offset < len(record["x"]):
                for j, value in enumerate(record["x"][offset]):
                    row[f"x{j + 1}"] = value
            experiment_rows.append(row)

        if not record["params"] or len(record["params"]) != n_params:
            continue

        params = np.asarray(record["params"], dtype=float)
        params_norm = normalize_parameters(params, lower, upper)
        true_norm = normalize_parameters(true_params, lower, upper)
        rms = float(np.linalg.norm(params_norm - true_norm) / np.sqrt(n_params))

        for j in range(n_params):
            history_rows.append({
                "noise": f"{record['noise']:.0e}",
                "total_experiments_used": n_exp,
                "parameter": f"p{j + 1}",
                "name": names[j],
                "estimate": params[j],
                "true_value": true_params[j],
                "relative_error": (params[j] - true_params[j]) / max(abs(true_params[j]), 1e-30),
                "rms_normalized_parameter_error": rms,
                "cumulative_information": record.get("information"),
            })

    return pd.DataFrame(history_rows), pd.DataFrame(experiment_rows)


def plot_all(history, experiments, constants, out_dir):
    n_params = int(constants.get("N_UNKNOWN_PARAMETERS", 9))
    true_params = np.asarray(constants["TRUE_PARAMS"], dtype=float)
    names = constants.get("PARAMETER_SHORT_NAMES", [f"p{i+1}" for i in range(n_params)])
    noises = sorted(history["noise"].unique())

    rows = int(np.ceil(n_params / 3))
    fig, axes = plt.subplots(rows, 3, figsize=(15, 4 * rows), squeeze=False)
    for j in range(n_params):
        ax = axes[j // 3][j % 3]
        for noise in noises:
            subset = history[(history["noise"] == noise) & (history["parameter"] == f"p{j+1}")]
            ax.plot(subset["total_experiments_used"], subset["estimate"],
                    marker="o", markersize=3, linewidth=1.4, label=f"noise {noise}")
        ax.axhline(true_params[j], color="black", linestyle="--", linewidth=1.2)
        ax.set_yscale("log")
        ax.set_title(f"p{j+1}: {names[j]}")
        ax.set_xlabel("Total experiments used")
        ax.grid(True, alpha=0.4)
        if j == 0:
            ax.legend(fontsize=8)
    for j in range(n_params, rows * 3):
        axes[j // 3][j % 3].axis("off")
    fig.suptitle("Parameter convergence (partial, from log)")
    fig.tight_layout()
    fig.savefig(out_dir / "01_parameter_convergence.png", dpi=200, bbox_inches="tight")
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 5))
    for noise in noises:
        subset = history[history["noise"] == noise].drop_duplicates("total_experiments_used")
        ax.plot(subset["total_experiments_used"], subset["rms_normalized_parameter_error"],
                marker="o", markersize=4, linewidth=1.6, label=f"noise {noise}")
    ax.set_yscale("log")
    ax.set_xlabel("Total experiments used")
    ax.set_ylabel("RMS normalized log-parameter error")
    ax.set_title("Parameter error (partial, from log)")
    ax.grid(True, alpha=0.4)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_dir / "02_rms_parameter_error.png", dpi=200, bbox_inches="tight")
    plt.close(fig)

    if not experiments.empty:
        fig, ax = plt.subplots(figsize=(8, 5))
        for noise in sorted(experiments["noise"].unique()):
            subset = experiments[experiments["noise"] == noise].sort_values("experiment")
            ax.plot(subset["experiment"], subset["methanol"],
                    marker="o", markersize=3, linewidth=1.2, label=f"noise {noise}")
        ax.set_xlabel("Experiment number")
        ax.set_ylabel("CH3OH outlet fraction")
        ax.set_title("Measured response (partial, from log)")
        ax.grid(True, alpha=0.4)
        ax.legend()
        fig.tight_layout()
        fig.savefig(out_dir / "03_response.png", dpi=200, bbox_inches="tight")
        plt.close(fig)

    if history["cumulative_information"].notna().any():
        fig, ax = plt.subplots(figsize=(8, 5))
        for noise in noises:
            subset = (history[history["noise"] == noise]
                      .drop_duplicates("total_experiments_used")
                      .dropna(subset=["cumulative_information"]))
            ax.plot(subset["total_experiments_used"], subset["cumulative_information"],
                    marker="o", markersize=4, linewidth=1.6, label=f"noise {noise}")
        ax.set_xlabel("Total experiments used")
        ax.set_ylabel("Cumulative information")
        ax.set_title("Information gain (partial, from log)")
        ax.grid(True, alpha=0.4)
        ax.legend()
        fig.tight_layout()
        fig.savefig(out_dir / "04_cumulative_information.png", dpi=200, bbox_inches="tight")
        plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("log", type=Path, help="SLURM .out file")
    parser.add_argument("--out", type=Path, default=None, help="output directory")
    parser.add_argument("--noise-order", default=None,
                        help="comma-separated noise levels overriding header order")
    parser.add_argument("--no-plots", action="store_true")
    args = parser.parse_args()

    lines = args.log.read_text(encoding="utf-8", errors="replace").splitlines()
    kind = detect_kind(args.log, lines)
    parse, script_name = PARSERS[kind]
    constants = load_script_constants(PROJECT_DIR / script_name)

    noises = ([float(v) for v in args.noise_order.split(",")]
              if args.noise_order else noise_headers(lines))
    if not noises:
        sys.exit("No 'Noise level:' headers found; pass --noise-order.")

    records, unmatched = parse(lines)
    records = assign_noise(records, noises)
    history, experiments = build_frames(records, noises, constants, kind)

    out_dir = args.out or (PROJECT_DIR / "results" / f"{args.log.stem}_partial")
    out_dir.mkdir(parents=True, exist_ok=True)

    history.to_csv(out_dir / "parameter_history.csv", index=False)
    experiments.to_csv(out_dir / "experiments.csv", index=False)
    with pd.ExcelWriter(out_dir / "variable_explorer_data.xlsx") as writer:
        history.to_excel(writer, sheet_name="parameter_history", index=False)
        experiments.to_excel(writer, sheet_name="experiments", index=False)

    if not args.no_plots and not history.empty:
        plot_all(history, experiments, constants, out_dir)

    print(f"job type          : {kind}")
    print(f"noise levels      : {', '.join(f'{v:.0e}' for v in noises)}")
    print(f"records parsed    : {len(records)}")
    print(f"estimations found : {history['total_experiments_used'].nunique() if not history.empty else 0}"
          f" experiment counts per noise")
    if not history.empty:
        for noise in sorted(history["noise"].unique()):
            subset = history[history["noise"] == noise]
            print(f"  noise {noise}: up to {subset['total_experiments_used'].max()} experiments, "
                  f"{subset['total_experiments_used'].nunique()} estimations")
    if not experiments.empty:
        has_x = [c for c in experiments.columns if c.startswith("x")]
        print(f"designs recovered : {'yes' if has_x else 'NO (not printed by this script)'}")
    if unmatched:
        print(f"rounds in flight  : {unmatched} started but not yet estimated")

    shared, isolated = check_continuity(
        records, noises, int(constants.get("N_UNKNOWN_PARAMETERS", 9))
    )
    if shared:
        print(f"\nEstimator instability, {len(shared)} rounds where every noise level "
              f"jumps together (expected: they share an initial design and seed):")
        for line in shared[:5]:
            print(line)
        if len(shared) > 5:
            print(f"  ... and {len(shared) - 5} more")
    if isolated:
        print(f"\nWARNING: {len(isolated)} rounds where only some noise levels jump. "
              f"These may be misattributed between noise levels:")
        for line in isolated[:5]:
            print(line)
        if len(isolated) > 5:
            print(f"  ... and {len(isolated) - 5} more")

    print(f"\nwritten to {out_dir}")


if __name__ == "__main__":
    main()
